const fs = require('fs');
const path = require('path');
const https = require('https');

const CONFIG = path.join(__dirname, 'config.js');

function httpJson(method, url, headers, body) {
  return new Promise((resolve, reject) => {
    const u = new URL(url);
    const opts = {
      hostname: u.hostname, port: u.port || 443, path: u.pathname + u.search,
      method,
      headers: Object.assign({ 'Content-Type': 'application/json' }, headers),
    };
    const r = https.request(opts, res => {
      let d = '';
      res.on('data', c => d += c);
      res.on('end', () => resolve({ status: res.statusCode, text: d }));
    });
    r.on('error', reject);
    r.setTimeout(30000, () => { r.destroy(); reject(new Error('timeout')); });
    if (body) r.write(body);
    r.end();
  });
}

async function renderPutEnv(key, value) {
  const sid = process.env.RENDER_SERVICE_ID;
  const r = await httpJson('PUT', 'https://api.render.com/v1/services/' + sid + '/env-vars/' + key,
    { 'Accept': 'application/json', 'Authorization': 'Bearer ' + process.env.RENDER_API_KEY },
    JSON.stringify({ value }));
  if (r.status !== 200) throw new Error('render put failed: ' + r.status);
}

async function renderCancelPendingDeploys() {
  const sid = process.env.RENDER_SERVICE_ID;
  const r = await httpJson('GET', 'https://api.render.com/v1/services/' + sid + '/deploys',
    { 'Accept': 'application/json', 'Authorization': 'Bearer ' + process.env.RENDER_API_KEY });
  let deps = [];
  try { deps = JSON.parse(r.text).map(x => x.deploy || x).filter(d => ['queued','created','build_in_progress','deploy_in_progress','update_in_progress'].includes(d.status)); } catch {}
  for (const d of deps) {
    try { await httpJson('POST', 'https://api.render.com/v1/services/' + sid + '/deploys/' + d.id + '/cancel',
      { 'Accept': 'application/json', 'Authorization': 'Bearer ' + process.env.RENDER_API_KEY }, '{}'); } catch {}
  }
}

async function renderTriggerDeploy() {
  await renderCancelPendingDeploys();
  const sid = process.env.RENDER_SERVICE_ID;
  const r = await httpJson('POST', 'https://api.render.com/v1/services/' + sid + '/deploys',
    { 'Accept': 'application/json', 'Authorization': 'Bearer ' + process.env.RENDER_API_KEY }, '{}');
  if (r.status !== 200 && r.status !== 201) throw new Error('render deploy failed: ' + r.status);
}

async function railwayUpsert(key, value, redeploy) {
  const q = JSON.stringify({
    query: 'mutation Upsert($projectId: String!, $environmentId: String!, $serviceId: String!, $name: String!, $value: String!) { variableUpsert(input: { projectId: $projectId, environmentId: $environmentId, serviceId: $serviceId, name: $name, value: $value }) }',
    variables: {
      projectId: process.env.RAILWAY_PROJECT_ID,
      environmentId: process.env.RAILWAY_ENVIRONMENT_ID,
      serviceId: process.env.RAILWAY_SERVICE_ID,
      name: key,
      value,
    },
  });
  const r = await httpJson('POST', 'https://backboard.railway.app/graphql/v2',
    { 'Authorization': 'Bearer ' + process.env.RAILWAY_TOKEN }, q);
  if (r.status !== 200) throw new Error('railway upsert failed: ' + r.status);
  const data = JSON.parse(r.text);
  if (data.errors) throw new Error('railway upsert error: ' + JSON.stringify(data.errors).substring(0, 120));
  if (redeploy) {
    await httpJson('POST', 'https://backboard.railway.app/graphql/v2',
      { 'Authorization': 'Bearer ' + process.env.RAILWAY_TOKEN },
      JSON.stringify({ query: 'mutation { serviceInstanceDeploy(environmentId: "' + process.env.RAILWAY_ENVIRONMENT_ID + '", serviceId: "' + process.env.RAILWAY_SERVICE_ID + '") }' }));
  }
}

function writeLocalConfig(cfg) {
  const lines = cfg.accounts.map(a => "  {n:" + JSON.stringify(a.n) + ", s:" + JSON.stringify(a.s) + "},").join('\n');
  const out = '// auto-generated by persist.js\nconst accounts = [\n' + lines + '\n];\n\nconst API_ID = ' + cfg.API_ID + ";\nconst API_HASH = " + JSON.stringify(cfg.API_HASH) + ";\nconst CHAT_ID = " + JSON.stringify(String(cfg.CHAT_ID)) + ";\n\nmodule.exports = { accounts, API_ID, API_HASH, CHAT_ID };\n";
  fs.writeFileSync(CONFIG, out);
}

// Persist full config {accounts, API_ID, API_HASH, CHAT_ID} everywhere possible.
// Returns list of backends that succeeded. Throws only if NONE succeeded.
async function persistConfig(cfg) {
  const ok = [];
  if (fs.existsSync(CONFIG)) {
    try { writeLocalConfig(cfg); ok.push('local'); } catch {}
  }
  if (process.env.RENDER_SERVICE_ID && process.env.RENDER_API_KEY) {
    try {
      await renderPutEnv('VOTE_CONFIG', JSON.stringify(cfg));
      await renderTriggerDeploy();
      ok.push('render');
    } catch {}
  }
  if (process.env.RAILWAY_TOKEN && process.env.RAILWAY_PROJECT_ID && process.env.RAILWAY_ENVIRONMENT_ID && process.env.RAILWAY_SERVICE_ID) {
    try {
      await railwayUpsert('VOTE_CONFIG', JSON.stringify(cfg), true);
      ok.push('railway');
    } catch {}
  }
  if (!ok.length) throw new Error('no persistence backend available');
  return ok;
}

// Persist a single env-var-backed state (e.g. SCHEDULE_STATE) — no redeploy needed.
async function persistState(key, obj) {
  const val = JSON.stringify(obj);
  if (fs.existsSync(path.join(__dirname, key === 'SCHEDULE_STATE' ? 'schedule-state.json' : key.toLowerCase() + '.json'))) {
    try { fs.writeFileSync(path.join(__dirname, key === 'SCHEDULE_STATE' ? 'schedule-state.json' : key.toLowerCase() + '.json'), val); } catch {}
  }
  if (process.env.RENDER_SERVICE_ID && process.env.RENDER_API_KEY) {
    renderPutEnv(key, val).catch(() => {});
  }
  if (process.env.RAILWAY_TOKEN && process.env.RAILWAY_PROJECT_ID && process.env.RAILWAY_ENVIRONMENT_ID && process.env.RAILWAY_SERVICE_ID) {
    railwayUpsert(key, val, false).catch(() => {});
  }
}

module.exports = { persistConfig, persistState };
